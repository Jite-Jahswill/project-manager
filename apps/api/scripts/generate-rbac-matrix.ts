/**
 * Writes docs/architecture/rbac-matrix.md from the permission registry and role
 * templates, so the documented matrix is always what the code enforces.
 * Run: pnpm api docs:rbac
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PERMISSIONS } from '../src/authz/permission-registry';
import { ROLE_TEMPLATES } from '../src/authz/role-templates';
import { PLATFORM_PERMISSIONS, PLATFORM_ROLE_TEMPLATES } from '../src/authz/platform-permission-registry';

const roles = ROLE_TEMPLATES;
const lines: string[] = [
  '# RBAC permission matrix',
  '',
  '> Generated by `pnpm api docs:rbac` from `apps/api/src/authz/*`. Do not edit by hand.',
  '',
  'These are the **starter templates** copied into each new organization. Owners can rename, edit, clone and delete',
  'them and create custom roles. **Owner** is a locked system role that holds every permission.',
  '',
  'Legend: ● granted. Scope **B** = branch-scopable (a role assigned at a branch grants it only there); **O** = organization-wide only;',
  '**O+** = organization-scoped catalog read that also takes effect through a branch-limited assignment.',
  'Any other **O** permission in a role assigned at a branch has no effect (the API reports it as `notAppliedAtBranch`).',
  'Sensitivity **R** = restricted (payroll, finance, sensitive HR, audit, exports).',
  '',
  '## Organization roles',
  '',
  `| Permission | Scope | Sens. | Owner | ${roles.map((r) => r.name).join(' | ')} |`,
  `|---|---|---|---|${roles.map(() => '---').join('|')}|`,
];
for (const p of PERMISSIONS.values()) {
  const cells = roles.map((r) => ((r.permissions as readonly string[]).includes(p.key) ? '●' : ''));
  lines.push(`| \`${p.key}\` | ${p.scope === 'BRANCH' ? 'B' : p.branchAssignable ? 'O+' : 'O'} | ${p.sensitivity === 'RESTRICTED' ? 'R' : ''} | ● | ${cells.join(' | ')} |`);
}
lines.push('', '## Platform roles', '', 'Platform permissions never grant access to organization business records.', '');
lines.push(`| Permission | Step-up | ${PLATFORM_ROLE_TEMPLATES.map((r) => r.name).join(' | ')} |`);
lines.push(`|---|---|${PLATFORM_ROLE_TEMPLATES.map(() => '---').join('|')}|`);
for (const p of PLATFORM_PERMISSIONS.values()) {
  const cells = PLATFORM_ROLE_TEMPLATES.map((r) => ((r.permissions as readonly string[]).includes(p.key) ? '●' : ''));
  lines.push(`| \`${p.key}\` | ${p.privileged ? 'yes' : ''} | ${cells.join(' | ')} |`);
}
const out = join(__dirname, '..', '..', '..', 'docs', 'architecture', 'rbac-matrix.md');
writeFileSync(out, lines.join('\n') + '\n');
console.log(`Wrote ${out}`);
